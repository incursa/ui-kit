import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sourcePath = join(root, "tokens", "incursa.tokens.json");
const check = process.argv.includes("--check");
const source = JSON.parse(await readFile(sourcePath, "utf8"));

assert.equal(source.version, "1.0.0", "token contract version must be explicit");

const tokens = [];
const byPath = new Map();

const walk = (node, path = [], inherited = {}) => {
    assert(node && typeof node === "object" && !Array.isArray(node), `token group ${path.join(".")} must be an object`);
    const extension = node.$extensions?.incursa ?? {};
    const context = { ...inherited, ...extension };

    if (Object.hasOwn(node, "$value")) {
        const tokenPath = path.join(".");
        const name = context.name ?? `${context.prefix ?? "inc-"}${path.at(-1)}`;
        assert(/^[a-z][a-z0-9-]*$/u.test(name), `${tokenPath} has invalid public name '${name}'`);
        assert(context.output === "theme" || context.output === "composition", `${tokenPath} must select a generated Sass output`);
        assert(!byPath.has(tokenPath), `duplicate token path ${tokenPath}`);

        const token = {
            path: tokenPath,
            name,
            output: context.output,
            value: node.$value,
            description: node.$description,
        };
        tokens.push(token);
        byPath.set(tokenPath, token);
        return;
    }

    for (const [key, value] of Object.entries(node)) {
        if (!key.startsWith("$")) walk(value, [...path, key], context);
    }
};

for (const [key, value] of Object.entries(source)) {
    if (!key.startsWith("$") && !["name", "version"].includes(key)) walk(value, [key]);
}

const aliasPattern = /^\{([^}]+)\}$/u;
const aliasTarget = (value) => typeof value === "string" ? value.match(aliasPattern)?.[1] : undefined;

for (const token of tokens) {
    const targetPath = aliasTarget(token.value);
    if (targetPath) assert(byPath.has(targetPath), `${token.path} references missing token ${targetPath}`);
}

const sassValue = (token) => {
    const targetPath = aliasTarget(token.value);
    if (targetPath) return `$${byPath.get(targetPath).name}`;
    return String(token.value);
};

const cssValue = (token) => {
    const targetPath = aliasTarget(token.value);
    if (targetPath) return `var(--${byPath.get(targetPath).name})`;
    return String(token.value);
};

const header = (sourceLabel) => `// Generated from ${sourceLabel} by scripts/build-tokens.mjs.\n// Do not edit this file directly.\n\n`;
const renderSass = (output) => header("tokens/incursa.tokens.json") + tokens
    .filter((token) => token.output === output)
    .map((token) => `${token.description ? `// ${token.description}\n` : ""}$${token.name}: ${sassValue(token)} !default;`)
    .join("\n") + "\n";

const css = `/* Generated from tokens/incursa.tokens.json by scripts/build-tokens.mjs. */\n:root {\n${tokens
    .map((token) => `  --${token.name}: ${cssValue(token)};`)
    .join("\n")}\n}\n`;

const outputs = new Map([
    [join(root, "src", "_inc-theme.scss"), renderSass("theme")],
    [join(root, "src", "_inc-composition-tokens.scss"), renderSass("composition")],
    [join(root, "dist", "incursa-tokens.css"), css],
]);

for (const [path, content] of outputs) {
    if (check) {
        const current = await readFile(path, "utf8").catch(() => "");
        assert.equal(current, content, `${path.slice(root.length + 1)} is stale; run npm run build:tokens`);
    } else {
        await writeFile(path, content);
    }
}

console.log(`${check ? "Verified" : "Generated"} ${tokens.length} design tokens across ${outputs.size} artifacts.`);
